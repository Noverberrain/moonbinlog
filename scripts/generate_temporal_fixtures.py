"""Build temporal protocol vectors from explicit calendar/duration components."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True
from generate_format_fixtures import event
from generate_table_map_fixtures import body

ROOT = Path(__file__).resolve().parents[1]


def fraction(microsecond, fsp):
    width = (fsp + 1) // 2
    divisor = [1, 10000, 100, 1][width]
    return (microsecond // divisor).to_bytes(width, "big")


def date_value(year, month, day):
    return (year * 512 + month * 32 + day).to_bytes(3, "little")


def datetime_value(year, month, day, hour, minute, second, microsecond, fsp):
    packed = (((((year * 13 + month) * 32 + day) * 32 + hour) * 64 + minute) * 64 + second)
    return (packed + (1 << 39)).to_bytes(5, "big") + fraction(microsecond, fsp)


def time_value(negative, hour, minute, second, microsecond, fsp):
    width = (fsp + 1) // 2
    integer = hour * 4096 + minute * 64 + second
    fractional = int.from_bytes(fraction(microsecond, fsp), "big")
    magnitude = integer * 256 ** width + fractional
    biased = (1 << 23) * 256 ** width + (-magnitude if negative else magnitude)
    return biased.to_bytes(3 + width, "big")


def generated_files():
    columns = [(10, None), (13, None)] + [(kind, fsp) for kind in [17, 18, 19] for fsp in range(7)]
    columns += [(17, 7), (18, 255), (19, 7), (7, None), (11, None), (12, None)]
    metadata = bytes(fsp for _, fsp in columns if fsp is not None)
    table = event(19, body(types=bytes(kind for kind, _ in columns), metadata=metadata,
                           nullable=b"\xff\xff\xff\x1f"))
    vectors = []
    invalid = []
    for year, month, day in [(0, 0, 0), (2026, 10, 21), (9999, 12, 31), (2024, 2, 29), (2023, 2, 31), (2026, 0, 0), (0, 12, 31)]:
        vectors.append((0, date_value(year, month, day), f"date:{year},{month},{day}"))
    for raw in [0, 1, 100, 126, 255]:
        vectors.append((1, bytes([raw]), f"year:{0 if raw == 0 else 1900 + raw}"))
    for fsp in range(7):
        unit = 10 ** (6 - fsp) if fsp else 0
        maximum = 1000000 - unit if fsp else 0
        for seconds, micro in [(0, 0), (4294967295, maximum), (1700000000, unit), (2147483648, 0)]:
            vectors.append((2 + fsp, seconds.to_bytes(4, "big") + fraction(micro, fsp), f"timestamp:{seconds},{micro}"))
        for fields in [(0, 0, 0, 0, 0, 0, 0), (2026, 10, 21, 12, 34, 56, maximum), (9999, 12, 31, 23, 59, 59, 0), (2023, 2, 31, 0, 0, 0, unit), (2026, 0, 0, 12, 0, 0, 0)]:
            vectors.append((9 + fsp, datetime_value(*fields, fsp), "datetime:" + ",".join(map(str, fields))))
        for fields in [(False, 0, 0, 0, 0), (True, 0, 0, 0, unit), (False, 12, 34, 56, maximum), (True, 12, 34, 56, maximum), (False, 838, 59, 59, 0), (True, 838, 59, 59, 0), (True, 0, 0, 1, 0)]:
            negative, hour, minute, second, micro = fields
            sign = int(negative and any([hour, minute, second, micro]))
            vectors.append((16 + fsp, time_value(*fields, fsp), f"time:{sign},{hour},{minute},{second},{micro}"))
    invalid.extend([(0, date_value(10000, 1, 1)), (0, date_value(2026, 13, 1)), (9, bytes(5))])
    for fields in [(10000, 1, 1, 0, 0, 0), (2026, 1, 1, 24, 0, 0), (2026, 1, 1, 0, 60, 0), (2026, 1, 1, 0, 0, 60)]:
        invalid.append((9, datetime_value(*fields, 0, 0)))
    for fsp in [1, 3, 5]:
        invalid.append((2 + fsp, bytes(4) + (1).to_bytes((fsp + 1) // 2, "big")))
        invalid.append((9 + fsp, datetime_value(2026, 1, 1, 0, 0, 0, 0, fsp)[:-1] + b"\x01"))
        invalid.append((16 + fsp, time_value(True, 0, 0, 0, [0, 10000, 100, 1][(fsp + 1) // 2], fsp)))
    invalid.extend([(4, bytes(4) + b"\x64"), (6, bytes(4) + b"\x27\x10"), (8, bytes(4) + b"\x0f\x42\x40")])
    for negative, hour, minute, second, micro in [(False, 839, 0, 0, 0), (False, 0, 60, 0, 0), (True, 0, 0, 60, 0), (False, 838, 59, 59, 1)]:
        invalid.append((22, time_value(negative, hour, minute, second, micro, 6)))
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_temporal_fixtures.py.", "", "///|", "let tm_temporal : Bytes = ["]
    for start in range(0, len(table), 10):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in table[start:start + 10]) + ",")
    lines.extend(["]", "", "///|", "let temporal_vectors : ReadOnlyArray[(Int32, Bytes, String)] = ["])
    for index, data, expected in vectors:
        encoded = "".join(f"\\x{byte:02x}" for byte in data)
        lines.append(f'  ({index}, b"{encoded}", "{expected}"),')
    lines.extend(["]", "", "///|", "let temporal_invalid : ReadOnlyArray[(Int32, Bytes)] = ["])
    for index, data in invalid:
        encoded = "".join(f"\\x{byte:02x}" for byte in data)
        lines.append(f'  ({index}, b"{encoded}"),')
    lines.append("]")
    canonical = [(i, b.hex(), s) for i, b, s in vectors] + [(i, b.hex()) for i, b in invalid]
    manifest = {"table_sha256": hashlib.sha256(table).hexdigest(), "columns": len(columns),
                "valid_vectors": len(vectors), "invalid_vectors": len(invalid),
                "vectors_sha256": hashlib.sha256(json.dumps(canonical, separators=(",", ":")).encode()).hexdigest()}
    return {ROOT / "temporal_fixture_test.mbt": "\n".join(lines) + "\n",
            ROOT / "fixtures" / "temporal" / "manifest.json": json.dumps(manifest, indent=2) + "\n"}, manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, manifest = generated_files()
    for path, expected in files.items():
        if args.check:
            def normalize(text):
                return re.sub(r",\)", ")", re.sub(r"\s+", "", text))
            if normalize(path.read_text(encoding="utf-8")) != normalize(expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {manifest['valid_vectors']} valid / {manifest['invalid_vectors']} invalid temporal vectors")


if __name__ == "__main__":
    main()
