"""Encode synthetic DECIMAL values using Python integers and Decimal text."""

import argparse
from decimal import Decimal, localcontext
import hashlib
import json
from pathlib import Path
import random
import re
import sys

sys.dont_write_bytecode = True
from generate_format_fixtures import event
from generate_table_map_fixtures import body

ROOT = Path(__file__).resolve().parents[1]
WIDTH = [0, 1, 1, 2, 2, 3, 3, 4, 4, 4]


def encode(unscaled, precision, scale):
    digits = str(abs(unscaled)).zfill(precision)
    integer = digits[:precision - scale]
    fraction = digits[precision - scale:]
    chunks = []
    if len(integer) % 9:
        split = len(integer) % 9
        chunks.append(integer[:split])
        integer = integer[split:]
    chunks.extend(integer[i:i + 9] for i in range(0, len(integer), 9))
    chunks.extend(fraction[i:i + 9] for i in range(0, len(fraction), 9))
    data = bytearray(b"".join(int(chunk).to_bytes(WIDTH[len(chunk)], "big") for chunk in chunks))
    if unscaled < 0:
        data = bytearray(byte ^ 255 for byte in data)
    data[0] ^= 128
    return bytes(data)


def generated_files():
    shapes = [(n, 0) for n in range(1, 10)] + [(n, n) for n in range(1, 10)]
    shapes += [(10, 2), (18, 9), (20, 10), (65, 0), (65, 30), (30, 30)]
    shapes += [(30, n) for n in range(10, 18)]
    invalid = [(0, 0), (66, 0), (5, 6), (40, 31), (255, 255)]
    metadata = bytes(x for shape in shapes + invalid for x in shape)
    columns = len(shapes) + len(invalid)
    table = event(19, body(types=bytes([246] * columns), metadata=metadata,
                           nullable=bytes([255] * ((columns + 7) // 8))))
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_decimal_fixtures.py.", "", "///|",
             "let tm_decimals : Bytes = ["]
    for start in range(0, len(table), 10):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in table[start:start + 10]) + ",")
    lines.extend(["]", "", "///|", "let decimal_shapes : ReadOnlyArray[(Int32, Int32)] = ["])
    lines.extend(f"  ({p}, {s})," for p, s in shapes)
    lines.extend(["]", "", "///|", "let decimal_vectors : ReadOnlyArray[(Int32, Bytes, String)] = ["])
    rng = random.Random(20261021)
    manifest = {"table_sha256": hashlib.sha256(table).hexdigest(), "shapes": shapes,
                "invalid_metadata": invalid, "vectors": []}
    with localcontext() as context:
        context.prec = 80
        for index, (precision, scale) in enumerate(shapes):
            maximum = 10 ** precision - 1
            values = {0, 1, -1, maximum, -maximum, rng.randrange(maximum + 1)}
            for value in sorted(values):
                data = encode(value, precision, scale)
                expected = format(Decimal(value).scaleb(-scale), "f")
                encoded = "".join(f"\\x{byte:02x}" for byte in data)
                lines.append(f'  ({index}, b"{encoded}", "{expected}"),')
                manifest["vectors"].append({"column": index, "hex": data.hex(), "text": expected})
    lines.append("]")
    vectors = manifest.pop("vectors")
    manifest["vector_count"] = len(vectors)
    manifest["vectors_sha256"] = hashlib.sha256(
        json.dumps(vectors, separators=(",", ":")).encode()).hexdigest()
    return {
        ROOT / "decimal_fixture_test.mbt": "\n".join(lines) + "\n",
        ROOT / "fixtures" / "decimal" / "manifest.json": json.dumps(manifest, indent=2) + "\n",
    }, len(vectors)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, count = generated_files()
    for path, expected in files.items():
        if args.check:
            def normalize(text):
                return re.sub(r",\)", ")", re.sub(r"\s+", "", text))
            if normalize(path.read_text(encoding="utf-8")) != normalize(expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {count} DECIMAL vectors")


if __name__ == "__main__":
    main()
