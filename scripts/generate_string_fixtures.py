"""Construct a CRC-protected table map for string boundary tests."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True
from generate_format_fixtures import event
from generate_table_map_fixtures import body

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    varchar = [0, 1, 255, 256, 600, 65535]
    char = [0, 1, 255, 256, 511, 512, 767, 768, 1023]
    metadata = b"".join(n.to_bytes(2, "little") for n in varchar)
    metadata += b"".join(bytes([254 ^ ((n // 256) * 16), n % 256]) for n in char)
    # STRING can disguise ENUM/SET; also include an invalid embedded type.
    metadata += bytes([247, 1, 248, 2, 0, 10])
    types = bytes([15] * len(varchar) + [254] * (len(char) + 3))
    data = event(19, body(types=types, metadata=metadata, nullable=b"\xff\xff\x03"))
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_string_fixtures.py.", "", "///|",
             "let tm_strings : Bytes = ["]
    for start in range(0, len(data), 10):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[start:start + 10]) + ",")
    lines.append("]")
    manifest = {"varchar_max_bytes": varchar, "string_max_bytes": char,
                "unsupported_embedded_types": [247, 248, 0],
                "event_bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    return {
        ROOT / "string_fixture_test.mbt": "\n".join(lines) + "\n",
        ROOT / "fixtures" / "string" / "manifest.json": json.dumps(manifest, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in generated_files().items():
        if args.check:
            if re.sub(r"\s+", "", path.read_text(encoding="utf-8")) != re.sub(r"\s+", "", expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} string TABLE_MAP fixture (18 columns)")


if __name__ == "__main__":
    main()
