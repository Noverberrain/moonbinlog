"""Construct BLOB metadata and little-endian prefix fixtures independently."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True
from generate_format_fixtures import event
from generate_table_map_fixtures import body

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    widths = [1, 2, 3, 4, 0, 5, 255]
    # JSON, geometry and standalone blob-family type codes are distinct inputs.
    types = bytes([252] * len(widths) + [245, 255, 249, 250, 251])
    metadata = bytes(widths + [4, 4, 1, 3, 4])
    samples = {"tm_blobs": event(19, body(types=types, metadata=metadata,
                                          nullable=b"\xff\x0f"))}
    for width in range(1, 5):
        payload = b"\0\xff" + "中文".encode("utf-8") + b"  "
        samples[f"blob_value_{width}"] = len(payload).to_bytes(width, "little") + payload
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_blob_fixtures.py."]
    for name, data in samples.items():
        lines.extend(["", "///|", f"let {name} : Bytes = ["])
        for start in range(0, len(data), 10):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[start:start + 10]) + ",")
        lines.append("]")
    manifest = {name: {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
                for name, data in samples.items()}
    return {
        ROOT / "blob_fixture_test.mbt": "\n".join(lines) + "\n",
        ROOT / "fixtures" / "blob" / "manifest.json": json.dumps(manifest, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in generated_files().items():
        if args.check:
            if re.sub(r"\s+", "", path.read_text(encoding="utf-8")) != re.sub(r"\s+", "", expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} 5 BLOB fixtures")


if __name__ == "__main__":
    main()
