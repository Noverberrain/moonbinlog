def generated_files():
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_table_map_fixtures.py; synthetic data."]
    manifest = {}
    for name, data in fixtures().items():
        lines.extend(["", "///|", f"let {name} : Bytes = ["])
        for start in range(0, len(data), 10):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[start:start + 10]) + ",")
        lines.append("]")
        manifest[name] = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    return {
        ROOT / "table_map_fixture_test.mbt": "\n".join(lines) + "\n",
        ROOT / "fixtures" / "table-map" / "manifest.json": json.dumps(manifest, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in generated_files().items():
        if args.check:
            if re.sub(r"\s+", "", path.read_text(encoding="utf-8")) != re.sub(r"\s+", "", expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {len(fixtures())} TABLE_MAP fixtures")


if __name__ == "__main__":
    main()
