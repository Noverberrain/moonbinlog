ROOT = Path(__file__).resolve().parents[1]
TYPES = bytes([8, 15, 246, 18, 252, 3, 1, 2, 9, 10])
METADATA = b"\x58\x02\x0a\x02\x06\x04"


def packed(number, width=None):
    if width is None:
        if number < 251:
            return bytes([number])
        width = 2 if number <= 0xffff else 3 if number <= 0xffffff else 8
    return bytes([{2: 0xfc, 3: 0xfd, 8: 0xfe}[width]]) + number.to_bytes(width, "little")


def prefix(table_id=0x010203040506, database=b"shop", table=b"orders", terminator=b"\0"):
    return (table_id.to_bytes(6, "little") + struct.pack("<H", 0x1234)
            + bytes([len(database)]) + database + terminator
            + bytes([len(table)]) + table + b"\0")


def body(types=TYPES, metadata=METADATA, nullable=b"\x95\x01", optional=b"",
         count_width=None, **names):
    return (prefix(**names) + packed(len(types), count_width) + types
            + packed(len(metadata)) + metadata + nullable + optional)


def tlv(kind, value):
    return bytes([kind]) + packed(len(value)) + value


def format_with_table_header(length):
    data = bytearray(fde()[:-4])
    data[76 + 18] = length
    return bytes(data) + struct.pack("<I", zlib.crc32(data))


