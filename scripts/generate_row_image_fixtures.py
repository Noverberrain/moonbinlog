"""Pack compact row NULL bitmaps and mixed values independently with Python."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import sys

sys.dont_write_bytecode = True
from generate_format_fixtures import event
from generate_table_map_fixtures import body
from generate_temporal_fixtures import datetime_value, date_value

ROOT = Path(__file__).resolve().parents[1]


def bitmap(indices, count):
    result = bytearray((count + 7) // 8)
    for index in indices:
        result[index // 8] |= 1 << (index % 8)
    return bytes(result)


def wire_samples():
    types = bytes([8, 15, 246, 18, 252, 3, 1, 2, 9, 10, 4, 5, 16, 254, 254, 254, 245])
    metadata = bytes([20, 0, 10, 2, 6, 4, 4, 8, 1, 1, 254, 4, 247, 2, 248, 8, 4])
    table = event(19, body(types=types, metadata=metadata, nullable=b"\xdf\xff\x01"))
    values = [bytes([255]) * 8, b"\x06" + "中文".encode(), bytes.fromhex("8000303943"),
              datetime_value(2026, 10, 22, 12, 34, 56, 123456, 6), b"\x03\0\0\0A\0B",
              struct.pack("<i", -2147483648), b"\xff", struct.pack("<h", -32768),
              (8388607).to_bytes(3, "little"), date_value(2026, 10, 22),
              struct.pack("<f", 1.5), struct.pack("<d", -2.5), b"\x01\x02", b"\x02hi",
              (256).to_bytes(2, "little"), (0x8000000000000005).to_bytes(8, "little"), b""]
    specs = {
        "full": (list(range(16)), []),
        "sparse": ([1, 5, 8, 14, 16], [1, 14, 16]),
        "nulls": ([0, 1, 4, 12, 16], [0, 1, 4, 12, 16]),
        "crossing": (list(range(16)), [0, 1, 7, 8, 12, 15]),
        "zero": ([0, 1, 2, 4, 6, 12, 16], [16]),
        "empty": ([], []),
    }
    zeros = {0: bytes(8), 1: b"\0", 2: b"\x80" + bytes(4), 4: bytes(4), 6: b"\0", 12: bytes(2)}
    samples = {"tm_row_image": table}
    manifest = {"table_sha256": hashlib.sha256(table).hexdigest(), "rows": {}}
    for name, (present, nulls) in specs.items():
        presence = bitmap(present, len(types))
        null_bitmap = bitmap([ordinal for ordinal, col in enumerate(present) if col in nulls], len(present))
        value_bytes = b"".join((zeros[col] if name == "zero" else values[col]) for col in present if col not in nulls)
        data = null_bitmap + value_bytes
        samples[f"row_{name}_present"] = presence
        samples[f"row_{name}"] = data
        manifest["rows"][name] = {"present_hex": presence.hex(), "null_hex": null_bitmap.hex(),
                                   "states": "".join("-" if i not in present else "N" if i in nulls else "V" for i in range(len(types))),
                                   "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    return samples, manifest


def generated_files():
    samples, manifest = wire_samples()
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_row_image_fixtures.py."]
    for name, data in samples.items():
        lines.extend(["", "///|", f"let {name} : Bytes = ["])
        for start in range(0, len(data), 10):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[start:start + 10]) + ",")
        lines.append("]")
    lines.extend(["", "///|", "let row_image_cases : ReadOnlyArray[(Bytes, Bytes, String)] = ["])
    for name in manifest["rows"]:
        lines.append(f'  (row_{name}_present, row_{name}, "{manifest["rows"][name]["states"]}"),')
    lines.append("]")
    return {ROOT / "row_image_fixture_test.mbt": "\n".join(lines) + "\n",
            ROOT / "fixtures" / "row-image" / "manifest.json": json.dumps(manifest, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in generated_files().items():
        if args.check:
            def normalize(text):
                return re.sub(r",([\)\]])", r"\1", re.sub(r"\s+", "", text))
            if normalize(path.read_text(encoding="utf-8")) != normalize(expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} 6 mixed row-image fixtures")


if __name__ == "__main__":
    main()
