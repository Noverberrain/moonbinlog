"""Verify fixed JSON captures and export official mysqlbinlog row images."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True
from verify_mysql_fixtures import event_offsets, quoted_bytes

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / 'fixtures/mysql-json'
PROFILES = ('crc32-full', 'crc32-minimal', 'off-full')


def oracle_images(dump):
    images, operations = [], []
    for line in dump.splitlines():
        if line.startswith((b'### INSERT INTO', b'### UPDATE', b'### DELETE FROM')):
            operations.append(line.split()[1].decode())
        elif line in (b'### SET', b'### WHERE'):
            images.append(['ABSENT', 'ABSENT'])
        elif match := re.fullmatch(rb'###\s+@([12])=(.*?) /\*.*', line):
            if not images:
                raise ValueError('row image without SET/WHERE')
            index = int(match[1]) - 1
            value = match[2]
            if value == b'NULL':
                text = 'NULL'
            elif index == 0:
                text = str(int(value))
            else:
                document = json.loads(bytes.fromhex(quoted_bytes(value)).decode('utf-8'))
                text = 'json:' + json.dumps(document, ensure_ascii=False, separators=(',', ':'))
            images[-1][index] = text
    if operations != ['INSERT', 'INSERT', 'INSERT', 'UPDATE', 'DELETE', 'DELETE'] or len(images) != 7:
        raise ValueError('unexpected JSON oracle operations')
    first = json.loads(images[0][1][5:])
    if first['u'] != 2**64 - 1 or first['i'] != -2**63:
        raise ValueError('JSON oracle integer precision lost')
    if images[1][1] != 'NULL' or images[2][1] != 'json:null':
        raise ValueError('SQL NULL and JSON null oracle mismatch')
    if any(image[0] == '99' for image in images):
        raise ValueError('rolled back JSON insert leaked')
    return images


def generated():
    manifest = json.loads((FIXTURES / 'manifest.json').read_text(encoding='utf-8'))
    for name in ['schema', 'workload']:
        text = (FIXTURES / f'{name}.sql').read_text(encoding='utf-8')
        if hashlib.sha256(text.encode()).hexdigest() != manifest[f'{name}_sha256']:
            raise ValueError(f'JSON capture SQL changed: {name}')
    lines = ['// Copyright 2026 Noverberrain.', '// SPDX-License-Identifier: Apache-2.0', '',
             '// Real MySQL JSON captures and official mysqlbinlog oracle.',
             '// Generated by scripts/verify_json_fixtures.py --write.']
    for name in PROFILES:
        raw = (FIXTURES / f'{name}.binlog').read_bytes()
        dump = (FIXTURES / f'{name}.mysqlbinlog.txt').read_bytes()
        entry = manifest['profiles'][name]
        if len(raw) != entry['bytes'] or hashlib.sha256(raw).hexdigest() != entry['sha256']:
            raise ValueError(f'JSON capture mismatch: {name}')
        if hashlib.sha256(dump).hexdigest() != entry['oracle_sha256']:
            raise ValueError(f'JSON oracle mismatch: {name}')
        if event_offsets(raw) != [int(n) for n in re.findall(rb'^# at (\d+)\r?$', dump, re.M)]:
            raise ValueError('JSON capture offsets differ from mysqlbinlog')
        key = name.replace('-', '_')
        lines += ['', '///|', f'let mysql_json_{key} : Bytes = [']
        for start in range(0, len(raw), 12):
            lines.append('  ' + ', '.join(f'0x{byte:02x}' for byte in raw[start:start + 12]) + ',')
        lines += [']', '', '///|', f'let mysql_json_{key}_oracle : ReadOnlyArray[ReadOnlyArray[String]] = [']
        for row in oracle_images(dump):
            lines.append('  [' + ', '.join(json.dumps(value, ensure_ascii=False) for value in row) + '],')
        lines.append(']')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    args = parser.parse_args()
    expected = generated()
    path = ROOT / 'mysql_json_fixture_test.mbt'
    if args.write:
        path.write_text(expected, encoding='utf-8', newline='\n')
    else:
        normalize = lambda text: re.sub(r',([\)\]])', r'\1', re.sub(r'\s+', '', text))
        if normalize(path.read_text(encoding='utf-8')) != normalize(expected):
            raise SystemExit('mysql_json_fixture_test.mbt differs')
    print('Verified 3 real JSON captures, CRCs, offsets and 42 official column positions')
