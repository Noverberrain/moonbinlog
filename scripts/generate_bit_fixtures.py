"""Construct all 64 BIT widths using Python arbitrary-precision integers."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True
from generate_format_fixtures import event
from generate_table_map_fixtures import body

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    invalid = [(0, 0), (8, 0), (255, 0), (0, 9), (1, 8), (7, 8), (255, 255)]
    metadata = bytes(x for n in range(1, 65) for x in [n % 8, n // 8])
    metadata += bytes(x for pair in invalid for x in pair)
    count = 64 + len(invalid)
    table = event(19, body(types=bytes([16] * count), metadata=metadata,
                           nullable=bytes([255] * ((count + 7) // 8))))
    vectors = []
    for n in range(1, 65):
        maximum = (1 << n) - 1
        for value in sorted({0, maximum, 0x0123456789abcdef & maximum}):
            data = value.to_bytes((n + 7) // 8, "big")
            vectors.append((n - 1, data, int.from_bytes(data, "big")))
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_bit_fixtures.py.", "", "///|", "let tm_bits : Bytes = ["]
    for start in range(0, len(table), 10):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in table[start:start + 10]) + ",")
    lines.extend(["]", "", "///|", "let bit_vectors : ReadOnlyArray[(Int32, Bytes, UInt64)] = ["])
    for index, data, value in vectors:
        encoded = "".join(f"\\x{byte:02x}" for byte in data)
        lines.append(f'  ({index}, b"{encoded}", {value}UL),')
    lines.append("]")
    canonical = [(i, b.hex(), str(v)) for i, b, v in vectors]
    manifest = {"valid_widths": 64, "invalid_metadata": invalid, "vectors": len(vectors),
                "table_sha256": hashlib.sha256(table).hexdigest(),
                "vectors_sha256": hashlib.sha256(json.dumps(canonical, separators=(",", ":")).encode()).hexdigest()}
    return {ROOT / "bit_fixture_test.mbt": "\n".join(lines) + "\n",
            ROOT / "fixtures" / "bit" / "manifest.json": json.dumps(manifest, indent=2) + "\n"}, len(vectors)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, count = generated_files()
    for path, expected in files.items():
        if args.check:
            def normalize(text):
                return re.sub(r",\)", ")", re.sub(r"\s+", "", text))
            if normalize(path.read_text(encoding="utf-8")) != normalize(expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {count} BIT vectors over all 64 widths")


if __name__ == "__main__":
    main()
