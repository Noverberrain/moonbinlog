"""Generate exact signed/unsigned vectors using Python int.from_bytes."""

import argparse
import hashlib
import json
from pathlib import Path
import random
import re

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    rng = random.Random(20261021)
    vectors = []
    # Indexes refer to the existing ten-column TABLE_MAP fixture.
    for index, width in [(6, 1), (7, 2), (8, 3), (5, 4), (0, 8)]:
        sign = 1 << (width * 8 - 1)
        mask = (1 << (width * 8)) - 1
        values = {0, 1, sign - 1, sign, sign + 1, mask - 1, mask,
                  0x0102030405060708 & mask}
        values.update(rng.getrandbits(width * 8) for _ in range(4))
        for value in sorted(values):
            data = value.to_bytes(width, "little")
            vectors.append((index, data, str(int.from_bytes(data, "little", signed=True)),
                            str(int.from_bytes(data, "little", signed=False))))
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_integer_fixtures.py using Python integers.",
             "", "///|",
             "let integer_vectors : ReadOnlyArray[(Int32, Bytes, String, String)] = ["]
    for index, data, signed, unsigned in vectors:
        encoded = "".join(f"\\x{byte:02x}" for byte in data)
        lines.append(f'  ({index}, b"{encoded}", "{signed}", "{unsigned}"),')
    lines.append("]")
    canonical = json.dumps([(i, b.hex(), s, u) for i, b, s, u in vectors], separators=(",", ":"))
    manifest = {"seed": 20261021, "vectors": len(vectors), "signedness_checks": len(vectors) * 2,
                "canonical_sha256": hashlib.sha256(canonical.encode()).hexdigest()}
    return {
        ROOT / "integer_fixture_test.mbt": "\n".join(lines) + "\n",
        ROOT / "fixtures" / "integer" / "manifest.json": json.dumps(manifest, indent=2) + "\n",
    }, len(vectors)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, count = generated_files()
    for path, expected in files.items():
        if args.check:
            # moon fmt adds trailing tuple commas when wrapping long vectors.
            def normalize(text):
                return re.sub(r",\)", ")", re.sub(r"\s+", "", text))
            if normalize(path.read_text(encoding="utf-8")) != normalize(expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {count} integer vectors ({count * 2} signedness cases)")


if __name__ == "__main__":
    main()
