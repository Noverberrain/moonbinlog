"""Build synthetic protocol fixtures with Python's independent zlib CRC32."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import zlib


ROOT = Path(__file__).resolve().parents[1]


def event(kind, body, checksum=True, flags=0):
    size = 19 + len(body) + (4 if checksum else 0)
    header = struct.pack("<IBIIIH", 0x01020304, kind, 7, size, 4 + size, flags)
    data = header + body
    if checksum:
        protected = bytearray(data)
        if kind == 15:
            protected[17] &= 0xFE
        data += struct.pack("<I", zlib.crc32(protected))
    return data


def fde(algorithm=1, version=b"8.0.36-moonbinlog", binlog_version=4,
        common_length=19, count=41, own_length=None, flags=0):
    if len(version) > 50:
        raise ValueError("server version exceeds the fixed field")
    lengths = bytearray(count)
    for kind, length in ((2, 13), (4, 8), (15, 57 + count),
                         (19, 8), (30, 10), (31, 10), (32, 10)):
        if kind <= count:
            lengths[kind - 1] = length
    if own_length is not None:
        lengths[14] = own_length
    body = (struct.pack("<H", binlog_version) + version.ljust(50, b"\0")
            + struct.pack("<IB", 0x65A0B1C2, common_length)
            + lengths + bytes([algorithm]))
    # An OFF policy still has a CRC-protected format-description event.
    return event(15, body, flags=flags)


def fixtures():
    return {
        "fde_crc32": fde(),
        "fde_off": fde(algorithm=0),
        "fde_in_use": fde(flags=1),
        "fde_other_flags": fde(flags=0x8001),
        "fde_bad_algorithm": fde(algorithm=2),
        "fde_bad_binlog_version": fde(binlog_version=3),
        "fde_other_server": fde(version=b"8.4.0"),
        "fde_bad_version_text": fde(version=b"8.0.x"),
        "fde_unterminated_version": fde(version=b"8" * 50),
        "fde_non_ascii_version": fde(version=b"8.0.36-\xff"),
        "fde_bad_common_length": fde(common_length=20),
        "fde_bad_table": fde(own_length=0),
        "fde_short_table": fde(count=14),
        "event_crc32": event(16, b"\x01\x00\x00\x00\x00\x00\x00\x00"),
        "event_off": event(16, b"\x01\x00\x00\x00\xaa\xbb\xcc\xdd", False),
        "empty_event_crc32": event(3, b""),
        "empty_event_off": event(3, b"", False),
    }


def generate():
    vectors = fixtures()
    lines = ["// Copyright 2026 Noverberrain.",
             "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_format_fixtures.py; synthetic data."]
    manifest = {}
    for name, data in vectors.items():
        lines.extend(["", "///|", f"let {name} : Bytes = ["])
        for start in range(0, len(data), 10):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[start:start + 10]) + ",")
        lines.append("]")
        manifest[name] = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    return {
        ROOT / "format_fixture_test.mbt": "\n".join(lines) + "\n",
        ROOT / "fixtures" / "format" / "manifest.json": json.dumps(manifest, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in generate().items():
        if args.check:
            actual = path.read_text(encoding="utf-8")
            # Moon's formatter may reflow arrays; compare the generated tokens.
            if re.sub(r"\s+", "", actual) != re.sub(r"\s+", "", expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {len(fixtures())} zlib-backed fixtures")


if __name__ == "__main__":
    main()
