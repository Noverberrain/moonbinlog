"""Verify captured files and export mysqlbinlog's row images to MoonBit tests."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "fixtures" / "mysql-8.0"
PROFILES = ("crc32-full", "crc32-minimal", "off-full")


def quoted_bytes(value):
    if not (value.startswith(b"'") and value.endswith(b"'")):
        raise ValueError(f"expected quoted bytes: {value!r}")
    data = value[1:-1]
    result = bytearray()
    cursor = 0
    escapes = {ord("0"): 0, ord("n"): 10, ord("r"): 13, ord("t"): 9,
               ord("b"): 8, ord("Z"): 26, ord("\\"): 92, ord("'"): 39, ord('"'): 34}
    while cursor < len(data):
        if data[cursor] != 92:
            result.append(data[cursor])
            cursor += 1
        elif data[cursor:cursor + 2] == b"\\x":
            result.append(int(data[cursor + 2:cursor + 4], 16))
            cursor += 4
        else:
            result.append(escapes[data[cursor + 1]])
            cursor += 2
    return result.hex()


def scalar(index, value):
    if value == b"NULL":
        return "NULL"
    if index in (5, 6, 18, 19):
        return "hex:" + quoted_bytes(value)
    text = value.decode("ascii")
    if index < 5:
        # mysqlbinlog prints both signed and unsigned interpretations if needed.
        unsigned = re.search(r"\((\d+)\)", text)
        return unsigned[1] if index == 4 and unsigned else text.split(" ")[0]
    if index == 8:
        return "date:" + ",".join(str(int(n)) for n in re.findall(r"\d+", text))
    if index == 10:
        return "datetime:" + ",".join(str(int(n)) for n in re.findall(r"\d+", text))
    if index == 11:
        return "time:" + ("-" if "-" in text else "+") + ",".join(str(int(n)) for n in re.findall(r"\d+", text))
    if index == 12:
        return "timestamp:" + text.replace(".", ",")
    if index in (15, 17):
        return str(int(text[2:-1], 2))
    return text


def oracle_images(dump):
    images, operations = [], []
    image = None
    for line in dump.splitlines():
        if line.startswith((b"### INSERT INTO", b"### UPDATE", b"### DELETE FROM")):
            operations.append(line.split()[1].decode())
        elif line in (b"### SET", b"### WHERE"):
            image = ["ABSENT"] * 20
            images.append(image)
        elif match := re.fullmatch(rb"###\s+@(\d+)=(.*?) /\*.*", line):
            index = int(match[1]) - 1
            if image is None or not 0 <= index < 20:
                raise ValueError("unexpected oracle row layout")
            image[index] = scalar(index, match[2].strip())
    if operations != ["INSERT", "INSERT", "UPDATE", "DELETE"] or len(images) != 5:
        raise ValueError("oracle does not contain the expected four committed changes")
    if images[0][4] != "18446744073709551615" or images[0][7] != "-12345678901234.123456":
        raise ValueError("oracle lost exact integer/decimal values")
    if any(row[0] == "99" for row in images):
        raise ValueError("rolled-back insert leaked into committed log")
    return images


def event_offsets(raw):
    if raw[:4] != b"\xfebin":
        raise ValueError("invalid captured file magic")
    cursor, offsets, algorithm = 4, [], None
    while cursor < len(raw):
        if len(raw) - cursor < 19:
            raise ValueError("truncated captured event header")
        size = struct.unpack_from("<I", raw, cursor + 9)[0]
        packet = raw[cursor:cursor + size]
        if size < 19 or len(packet) != size:
            raise ValueError("truncated captured event")
        kind = packet[4]
        if kind == 15:
            algorithm = packet[-5]
        if algorithm not in (0, 1):
            raise ValueError("missing/unsupported captured FDE")
        if kind == 15 or algorithm == 1:
            protected = bytearray(packet[:-4])
            if kind == 15:
                protected[17] &= 0xFE
            if zlib.crc32(protected) != struct.unpack("<I", packet[-4:])[0]:
                raise ValueError("captured CRC mismatch")
        offsets.append(cursor)
        cursor += size
    return offsets


def generated():
    manifest = json.loads((FIXTURES / "manifest.json").read_text(encoding="utf-8"))
    for filename, field in [("schema.sql", "schema_sha256"), ("workload.sql", "workload_sha256")]:
        text = (FIXTURES / filename).read_text(encoding="utf-8")
        if hashlib.sha256(text.encode()).hexdigest() != manifest[field]:
            raise ValueError(f"capture SQL changed: {filename}")
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Exported from real MySQL captures and official mysqlbinlog output.",
             "// Generated by scripts/verify_mysql_fixtures.py --write; not synthetic data."]
    for name in PROFILES:
        raw = (FIXTURES / f"{name}.binlog").read_bytes()
        dump = (FIXTURES / f"{name}.mysqlbinlog.txt").read_bytes()
        entry = manifest["profiles"][name]
        if len(raw) != entry["bytes"] or hashlib.sha256(raw).hexdigest() != entry["sha256"]:
            raise ValueError(f"capture digest mismatch: {name}")
        if hashlib.sha256(dump).hexdigest() != entry["oracle_sha256"]:
            raise ValueError(f"oracle digest mismatch: {name}")
        offsets = event_offsets(raw)
        if offsets != [int(n) for n in re.findall(rb"^# at (\d+)\r?$", dump, re.M)]:
            raise ValueError(f"mysqlbinlog event offsets differ: {name}")
        prefix = "mysql_" + name.replace("-", "_")
        lines.extend(["", "///|", f"let {prefix} : Bytes = ["])
        for start in range(0, len(raw), 14):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in raw[start:start + 14]) + ",")
        lines.extend([
            "]", "", "///|", f"let {prefix}_offsets : ReadOnlyArray[UInt64] = [",
            "  " + ", ".join(str(n) + "UL" for n in offsets) + ",", "]", "", "///|",
            f"let {prefix}_oracle : ReadOnlyArray[ReadOnlyArray[String]] = [",
        ])
        for image in oracle_images(dump):
            lines.extend(["  [", "    " + ", ".join(json.dumps(n) for n in image) + ",", "  ],"])
        lines.append("]")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = generated()
    output = ROOT / "mysql_fixture_test.mbt"
    if args.write:
        output.write_text(expected, encoding="utf-8", newline="\n")
    else:
        def normalize(text):
            return re.sub(r",([\)\]])", r"\1", re.sub(r"\s+", "", text))
        if normalize(output.read_text(encoding="utf-8")) != normalize(expected):
            raise SystemExit("mysql_fixture_test.mbt differs; run --write")
    print("Verified 3 real captures, CRCs, mysqlbinlog offsets and 15 oracle row images")
