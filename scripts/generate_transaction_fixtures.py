"""Build transaction boundary events and contiguous synthetic RBR streams."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import sys
import zlib

sys.dont_write_bytecode = True
from generate_format_fixtures import event, fde
from generate_row_image_fixtures import wire_samples
from generate_rows_event_fixtures import fixtures as row_events

ROOT = Path(__file__).resolve().parents[1]


def query(sql, database=b"", status=b"", error=0, checksum=True):
    fixed = struct.pack("<IIBHH", 123, 0, len(database), error, len(status))
    return event(2, fixed + status + database + b"\0" + sql, checksum)


def stream(packets, checksum=True):
    position = 4
    chunks = []
    for packet in packets:
        patched = bytearray(packet)
        position += len(packet)
        struct.pack_into("<I", patched, 13, position)
        if checksum:
            patched[-4:] = struct.pack("<I", zlib.crc32(patched[:-4]))
        chunks.append(bytes(patched))
    return b"".join(chunks)


def fixtures():
    rows = row_events()
    samples, _ = wire_samples()
    begin = query(b"BEGIN")
    commit = query(b"COMMIT")
    rollback = query(b"ROLLBACK")
    xid = event(16, (0xfedcba9876543210).to_bytes(8, "little"))
    maps = {
        "tx_begin": begin, "tx_commit": commit, "tx_rollback": rollback,
        "tx_begin_decorated": query(b" \tbeGIn ;\r\n", b"shop", b"\x00\0\0\0\0"),
        "tx_commit_decorated": query(b"\ncoMMit; \t"),
        "tx_rollback_decorated": query(b" rOLlBAck ; "),
        "tx_xid": xid, "tx_xid_zero": event(16, bytes(8)),
        "tx_xid_short": event(16, bytes(7)), "tx_xid_long": event(16, bytes(9)),
        "tx_query_short": event(2, bytes(12)),
        "tx_status_overrun": event(2, struct.pack("<IIBHH", 0, 0, 0, 0, 65535) + b"\0BEGIN"),
        "tx_database_terminator": event(2, struct.pack("<IIBHH", 0, 0, 4, 0, 0) + b"shopXBEGIN"),
        "tx_database_nul": query(b"BEGIN", b"sh\0p"),
        "tx_query_failed": query(b"COMMIT", error=1234),
        "tx_false_commit": query(b"INSERT INTO log VALUES ('COMMIT')"),
        "tx_multi_query": query(b"COMMIT; DELETE FROM t"),
        "tx_savepoint": query(b"ROLLBACK TO SAVEPOINT x"),
        "tx_chain": query(b"COMMIT AND CHAIN"),
        "tx_double_semicolon": query(b"COMMIT;;"),
        "tx_comment": query(b"COMMIT /* comment */"),
        "tx_empty_sql": query(b" \t"),
        "tx_nonascii": query(b"COMMIT\xc0"),
        "tx_unknown": event(29, b"ignored?"),
    }
    bad_crc = bytearray(begin)
    bad_crc[-1] ^= 1
    maps["tx_bad_crc"] = bytes(bad_crc)
    for name, index, length in [("fde_tx_bad_query", 1, 8), ("fde_tx_bad_xid", 15, 8)]:
        format_bytes = bytearray(fde()[:-4])
        format_bytes[76 + index] = length
        maps[name] = bytes(format_bytes) + struct.pack("<I", zlib.crc32(format_bytes))
    table = samples["tm_row_image"]
    prefix = [begin, table, rows["rows_write_end"]]
    maps["tx_stream_commit"] = stream(prefix + [xid])
    maps["tx_stream_rollback"] = stream(prefix + [rollback])
    maps["tx_stream_two_statements"] = stream(prefix + [table, rows["rows_delete_two"], commit])
    maps["tx_stream_two_transactions"] = stream(prefix + [xid] + prefix + [commit])
    maps["tx_stream_unfinished"] = stream(prefix)
    maps["tx_stream_two_rows"] = stream([begin, table, rows["rows_write_two"], xid])
    maps["tx_stream_updates"] = stream([begin, table, rows["rows_update_two"], xid])
    maps["tx_stream_unknown"] = stream(prefix + [maps["tx_unknown"], xid])
    maps["tx_stream_off"] = stream([query(b"BEGIN", checksum=False), rows["tm_row_image_off"],
                                      rows["rows_off"], event(16, bytes(8), False)], checksum=False)
    return maps


def generated_files():
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_transaction_fixtures.py."]
    manifest = {}
    for name, data in fixtures().items():
        lines.extend(["", "///|", f"let {name} : Bytes = ["])
        for start in range(0, len(data), 12):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[start:start + 12]) + ",")
        lines.append("]")
        manifest[name] = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    return {ROOT / "transaction_fixture_test.mbt": "\n".join(lines) + "\n",
            ROOT / "fixtures" / "transaction" / "manifest.json": json.dumps(manifest, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in generated_files().items():
        if args.check:
            def normalize(text):
                return re.sub(r",([\)\]])", r"\1", re.sub(r"\s+", "", text))
            if normalize(path.read_text(encoding="utf-8")) != normalize(expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {len(fixtures())} transaction fixtures")


if __name__ == "__main__":
    main()
