"""Construct raw ENUM ordinals and SET masks independently using Python ints."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True
from generate_format_fixtures import event
from generate_table_map_fixtures import body

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    valid = [(247, 1), (247, 2)] + [(248, n) for n in [1, 2, 3, 4, 8]]
    invalid = [(247, n) for n in [0, 3, 8, 255]]
    invalid += [(248, n) for n in [0, 5, 6, 7, 9, 255]] + [(0, 1), (254, 10), (231, 1)]
    metadata = bytes(x for pair in valid + invalid + [(247, 1), (248, 8)] for x in pair)
    types = bytes([254] * (len(valid) + len(invalid)) + [247, 248])
    table = event(19, body(types=types, metadata=metadata,
                           nullable=bytes([255] * ((len(types) + 7) // 8))))
    vectors = []
    for index, (tag, width) in enumerate(valid):
        maximum = (1 << (width * 8)) - 1
        for value in sorted({0, 1, maximum, 1 << (width * 8 - 1), 0x0123456789abcdef & maximum}):
            data = value.to_bytes(width, "little")
            vectors.append((index, data, tag, int.from_bytes(data, "little")))
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_enum_set_fixtures.py.", "", "///|", "let tm_enum_set : Bytes = ["]
    for start in range(0, len(table), 10):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in table[start:start + 10]) + ",")
    lines.extend(["]", "", "///|", "let enum_set_vectors : ReadOnlyArray[(Int32, Bytes, Int32, UInt64)] = ["])
    for index, data, tag, expected in vectors:
        encoded = "".join(f"\\x{byte:02x}" for byte in data)
        lines.append(f'  ({index}, b"{encoded}", {tag}, {expected}UL),')
    lines.append("]")
    canonical = [(i, b.hex(), tag, str(v)) for i, b, tag, v in vectors]
    manifest = {"valid_metadata": valid, "invalid_metadata": invalid, "vectors": len(vectors),
                "table_sha256": hashlib.sha256(table).hexdigest(),
                "vectors_sha256": hashlib.sha256(json.dumps(canonical, separators=(",", ":")).encode()).hexdigest()}
    return {ROOT / "enum_set_fixture_test.mbt": "\n".join(lines) + "\n",
            ROOT / "fixtures" / "enum-set" / "manifest.json": json.dumps(manifest, indent=2) + "\n"}, len(vectors)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, count = generated_files()
    for path, expected in files.items():
        if args.check:
            def normalize(text):
                return re.sub(r",\)", ")", re.sub(r"\s+", "", text))
            if normalize(path.read_text(encoding="utf-8")) != normalize(expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {count} ENUM/SET vectors")


if __name__ == "__main__":
    main()
