"""Build IEEE-754 vectors with Python struct, without MoonBit conversions."""

import argparse
import hashlib
import json
import math
from pathlib import Path
import random
import re
import struct
import sys

sys.dont_write_bytecode = True
from generate_format_fixtures import event
from generate_table_map_fixtures import body

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    table = event(19, body(types=bytes([4, 5, 4, 4, 4, 5, 5, 5]),
                           metadata=bytes([4, 8, 0, 8, 255, 0, 4, 255]), nullable=b"\xff"))
    values = []
    invalid = []
    rng = random.Random(20261021)
    for index, width, fmt, edge in [(0, 4, "f", [0, 1, 0x7fffff, 0x800000, 0x7f7fffff]),
                                    (1, 8, "d", [0, 1, 0xfffffffffffff, 0x10000000000000, 0x7fefffffffffffff])]:
        sign = 1 << (width * 8 - 1)
        patterns = set(edge + [bits | sign for bits in edge])
        for value in [1.0, -1.0, 0.1, -123.5, 16777217.0, 9007199254740991.0]:
            patterns.add(int.from_bytes(struct.pack("<" + fmt, value), "little"))
        patterns.update(rng.getrandbits(width * 8) for _ in range(16))
        exponent = 0x7f800000 if width == 4 else 0x7ff0000000000000
        quiet = 0x400000 if width == 4 else 0x8000000000000
        for bits in [exponent, sign | exponent, exponent | 1, exponent | quiet | 0x123, sign | exponent | quiet]:
            invalid.append((index, bits.to_bytes(width, "little"), bits))
        for bits in sorted(patterns):
            data = bits.to_bytes(width, "little")
            value = struct.unpack("<" + fmt, data)[0]
            if math.isfinite(value):
                literal = re.sub(r"^(-?\d+)e", r"\1.0e", repr(value))
                values.append((index, data, bits, literal))
            else:
                invalid.append((index, data, bits))
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_floating_fixtures.py.", "", "///|", "let tm_floating : Bytes = ["]
    for start in range(0, len(table), 10):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in table[start:start + 10]) + ",")
    lines.extend(["]", "", "///|", "let floating_vectors : ReadOnlyArray[(Int32, Bytes, UInt64, Double)] = ["])
    for index, data, bits, expected in values:
        encoded = "".join(f"\\x{b:02x}" for b in data)
        lines.append(f'  ({index}, b"{encoded}", {bits}UL, {expected}),')
    lines.extend(["]", "", "///|", "let floating_nonfinite : ReadOnlyArray[(Int32, Bytes, UInt64)] = ["])
    for index, data, bits in invalid:
        encoded = "".join(f"\\x{b:02x}" for b in data)
        lines.append(f'  ({index}, b"{encoded}", {bits}UL),')
    lines.append("]")
    canonical = [(i, b.hex(), str(bits), expected) for i, b, bits, expected in values]
    canonical += [(i, b.hex(), str(bits)) for i, b, bits in invalid]
    manifest = {"seed": 20261021, "table_sha256": hashlib.sha256(table).hexdigest(),
                "finite_vectors": len(values), "nonfinite_vectors": len(invalid),
                "vectors_sha256": hashlib.sha256(json.dumps(canonical, separators=(",", ":")).encode()).hexdigest()}
    return {ROOT / "floating_fixture_test.mbt": "\n".join(lines) + "\n",
            ROOT / "fixtures" / "floating" / "manifest.json": json.dumps(manifest, indent=2) + "\n"}, manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, manifest = generated_files()
    for path, expected in files.items():
        if args.check:
            def normalize(text):
                return re.sub(r",\)", ")", re.sub(r"\s+", "", text))
            if normalize(path.read_text(encoding="utf-8")) != normalize(expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {manifest['finite_vectors']} finite / {manifest['nonfinite_vectors']} nonfinite floating vectors")


if __name__ == "__main__":
    main()
