"""Independently encode MySQL 8.0 previous-GTID sets using struct/zlib."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import sys
import tempfile
import uuid
import zlib

sys.dont_write_bytecode = True
from generate_format_fixtures import event, fde

ROOT = Path(__file__).resolve().parents[1]
SID_A = bytes.fromhex('00112233445566778899aabbccddeeff')
SID_B = bytes.fromhex('ffeeddccbbaa99887766554433221100')
MAX_GNO_END = 2**63 - 1


def body(entries):
    result = struct.pack('<Q', len(entries))
    for sid, intervals in entries:
        result += sid + struct.pack('<Q', len(intervals))
        result += b''.join(struct.pack('<QQ', start, end) for start, end in intervals)
    return result


def fixtures():
    valid = {
        'empty': [],
        'single': [(SID_A, [(1, 2)])],
        'multiple': [(SID_A, [(1, 5), (8, 10)]), (SID_B, [(2**32, 2**32 + 2)])],
        'boundary': [(bytes(16), [(MAX_GNO_END - 1, MAX_GNO_END)])],
        # MySQL's decoder accepts these; retain entries instead of normalizing.
        'wire_order': [(SID_B, []), (SID_A, [(1, 2)]), (SID_A, [(9, 12)])],
    }
    invalid = {f'short_count_{n}': bytes(n) for n in range(8)}
    invalid.update({
        'huge_sids': struct.pack('<Q', 2**64 - 1),
        'missing_sid': struct.pack('<Q', 1) + bytes(23),
        'huge_intervals': struct.pack('<Q', 1) + SID_A + struct.pack('<Q', 2**64 - 1),
        'missing_interval': struct.pack('<Q', 1) + SID_A + struct.pack('<Q', 1) + bytes(15),
        'missing_second_sid': struct.pack('<Q', 2) + SID_A + struct.pack('<Q', 1) + struct.pack('<QQ', 1, 2) + bytes(8),
        'trailing_empty': body([]) + b'\0',
        'trailing_nonempty': body(valid['single']) + b'\0',
    })
    for name, intervals in {
        'zero_start': [(0, 2)], 'zero_end': [(1, 0)], 'empty_interval': [(5, 5)],
        'reversed': [(5, 4)], 'negative_start': [(2**64 - 1, 2)],
        'high_end': [(1, 2**63)], 'unsigned_max_end': [(1, 2**64 - 1)],
        'overlap': [(1, 5), (4, 7)], 'adjacent': [(1, 5), (5, 8)],
        'unordered': [(8, 10), (1, 3)],
    }.items():
        invalid[name] = body([(SID_A, intervals)])
    return valid, invalid


def literal(data):
    return 'b"' + ''.join(f'\\x{x:02x}' for x in data) + '"'


def generated():
    valid, invalid = fixtures()
    lines = ['// Copyright 2026 Noverberrain.', '// SPDX-License-Identifier: Apache-2.0', '',
             '// Generated by scripts/generate_previous_gtids_fixtures.py; synthetic sets.']
    manifest = {'valid': {}, 'invalid': {}, 'real_empty_oracles': []}
    for name, entries in valid.items():
        for checksum in [True, False]:
            data = event(35, body(entries), checksum=checksum)
            key = f'pg_{name}_{"crc32" if checksum else "off"}'
            lines += ['', '///|', f'let {key} : Bytes = {literal(data)}']
            manifest['valid'][key] = {'sha256': hashlib.sha256(data).hexdigest(),
                                      'sids': [{'sid_hex': sid.hex(), 'intervals': intervals}
                                               for sid, intervals in entries]}
    bad_crc = bytearray(event(35, body(valid['single'])))
    bad_crc[-1] ^= 1
    bad_fde = bytearray(fde())
    bad_fde[76 + 34] = 1
    bad_fde[-4:] = struct.pack('<I', zlib.crc32(bad_fde[:-4]))
    for name, data in [('pg_bad_crc', bytes(bad_crc)), ('pg_bad_post_header', bytes(bad_fde)),
                       ('pg_missing_post_header', fde(count=34))]:
        lines += ['', '///|', f'let {name} : Bytes = {literal(data)}']
    lines += ['', '///|', 'let pg_invalid : ReadOnlyArray[(String, Bytes)] = [']
    for name, payload in invalid.items():
        data = event(35, payload)
        lines.append(f'  ("{name}", {literal(data)}),')
        manifest['invalid'][name] = hashlib.sha256(data).hexdigest()
    lines.append(']')
    lines += ['', '///|', 'fn pg_real_empty() -> Array[Bytes] {', '  [']
    for family, prefix in [('mysql-8.0', 'mysql'), ('mysql-json', 'mysql_json')]:
        folder = ROOT / 'fixtures' / family
        captures = json.loads((folder / 'manifest.json').read_text(encoding='utf-8'))
        for profile in ['crc32-full', 'crc32-minimal', 'off-full']:
            raw = (folder / f'{profile}.binlog').read_bytes()
            dump = (folder / f'{profile}.mysqlbinlog.txt').read_bytes()
            expected = captures['profiles'][profile]
            assert hashlib.sha256(raw).hexdigest() == expected['sha256']
            assert hashlib.sha256(dump).hexdigest() == expected['oracle_sha256']
            assert len(re.findall(rb'Previous-GTIDs\r?\n# \[empty\]', dump)) == 1
            lines.append(f'    {prefix}_{profile.replace("-", "_")},')
            manifest['real_empty_oracles'].append({'capture': f'{family}/{profile}',
                                                  'sha256': expected['sha256'],
                                                  'oracle_sha256': expected['oracle_sha256']})
    lines += ['  ]', '}']
    return {ROOT / 'previous_gtids_fixture_test.mbt': '\n'.join(lines) + '\n',
            ROOT / 'fixtures/previous-gtids/manifest.json': json.dumps(manifest, indent=2) + '\n'}


def verify_mysqlbinlog(executable):
    """Optional local oracle; normal CI never requires an installed MySQL tool."""
    version = subprocess.run([executable, '--version'], capture_output=True, text=True, check=True)
    print(version.stdout.strip())
    count = 0
    with tempfile.TemporaryDirectory(prefix='moonbinlog-previous-gtids-') as folder:
        for name, entries in fixtures()[0].items():
            if name == 'wire_order':  # Its raw entries intentionally are not a normalized set.
                continue
            expected = []
            for sid, intervals in entries:
                ranges = [str(start) if end == start + 1 else f'{start}-{end - 1}'
                          for start, end in intervals]
                expected.append(str(uuid.UUID(bytes=sid)) + ':' + ':'.join(ranges))
            if not expected:
                expected = ['[empty]']
            for checksum in [True, False]:
                format_data = fde(algorithm=int(checksum))
                raw = bytearray(event(35, body(entries), checksum=checksum))
                struct.pack_into('<I', raw, 13, 4 + len(format_data) + len(raw))
                if checksum:
                    raw[-4:] = struct.pack('<I', zlib.crc32(raw[:-4]))
                path = Path(folder) / f'{name}-{checksum}.binlog'
                path.write_bytes(b'\xfebin' + format_data + raw)
                result = subprocess.run([executable, '--verify-binlog-checksum', str(path)],
                                        capture_output=True, text=True, check=True)
                actual = re.findall(r'^# (\[empty\]|[0-9a-f-]{36}:[0-9:-]+),?$', result.stdout, re.M)
                assert actual == expected, (name, checksum, actual, expected)
                count += 1
    print(f'Official mysqlbinlog matched {count} canonical synthetic sets (CRC32/OFF)')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--mysqlbinlog', help='Optional path for an independent local tool comparison')
    args = parser.parse_args()
    for path, expected in generated().items():
        if args.check:
            normalize = lambda text: re.sub(r',([\)\]])', r'\1', re.sub(r'\s+', '', text))
            assert normalize(path.read_text(encoding='utf-8')) == normalize(expected), path
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding='utf-8', newline='\n')
    valid, invalid = fixtures()
    print(f'{"Verified" if args.check else "Generated"} {len(valid) * 2} valid / {len(invalid)} invalid previous-GTID vectors and 6 empty real oracles')
    if args.mysqlbinlog:
        verify_mysqlbinlog(args.mysqlbinlog)
