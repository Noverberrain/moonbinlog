"""Wrap independently packed images in MySQL v2 ROWS events with zlib CRC."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import sys
import zlib

sys.dont_write_bytecode = True
from generate_format_fixtures import event, fde
from generate_table_map_fixtures import packed
from generate_row_image_fixtures import wire_samples

ROOT = Path(__file__).resolve().parents[1]
TABLE_ID = 0x010203040506


def fixtures():
    sample, _ = wire_samples()
    full, sparse = sample["row_full"], sample["row_sparse"]
    full_mask, sparse_mask = sample["row_full_present"], sample["row_sparse_present"]

    def body(kind=30, flags=0, table_id=TABLE_ID, extra=b"", count_wire=None,
             first=full_mask, second=sparse_mask, images=full):
        return (table_id.to_bytes(6, "little") + struct.pack("<HH", flags, len(extra) + 2)
                + extra + (packed(17) if count_wire is None else count_wire) + first
                + (second if kind == 31 else b"") + images)

    valid = body()
    maps = {
        "rows_write_two": event(30, body(images=full + full)),
        "rows_write_end": event(30, body(flags=1)),
        "rows_header_end_only": event(30, valid, flags=1),
        "rows_delete_two": event(32, body(kind=32, first=sparse_mask, images=sparse + sparse)),
        "rows_update_two": event(31, body(kind=31, images=full + sparse + full + sparse)),
        "rows_extra": event(30, body(extra=b"\x7fabc")),
        "rows_off": event(30, valid, False),
        "rows_empty": event(30, body(flags=1, images=b"")),
        "rows_padding": event(30, body(first=b"\xff\xff\xfe")),
        "rows_empty_before": event(31, body(kind=31, first=bytes(3), images=sparse)),
        "rows_half_update": event(31, body(kind=31, images=full)),
        "rows_second_short": event(30, body(images=full + full[:-1])),
        "rows_trailing_byte": event(30, body(images=full + b"\0")),
        "rows_no_progress": event(30, body(first=bytes(3), images=b"x")),
        "rows_pair_no_progress": event(31, body(kind=31, first=bytes(3), second=bytes(3), images=b"x")),
        "rows_wrong_count": event(30, body(count_wire=packed(18))),
        "rows_zero_count": event(30, body(count_wire=packed(0))),
        "rows_huge_count": event(30, body(count_wire=b"\xfe" + bytes([255]) * 8)),
        "rows_null_count": event(30, body(count_wire=b"\xfb")),
        "rows_reserved_count": event(30, body(count_wire=b"\xff")),
        "rows_short_count": event(30, valid[:10] + b"\xfc\x01"),
        "rows_short_first": event(30, body(first=b"\xff\xff", images=b"")),
        "rows_short_second": event(31, body(kind=31, second=b"\xff\xff", images=b"")),
        "rows_short_body": event(30, b""),
        "rows_extra_too_short": event(30, valid[:8] + b"\x01\0" + valid[10:]),
        "rows_extra_too_long": event(30, valid[:8] + b"\xff\xff" + valid[10:]),
        "rows_unknown_table": event(30, body(table_id=TABLE_ID + 1)),
        "rows_legacy": event(23, valid),
        "rows_partial": event(39, valid),
        "rows_not_nullable": event(30, body(images=b"\x20" + full[1:])),
        "tm_row_image_off": event(19, sample["tm_row_image"][19:-4], False),
    }
    for width in [2, 3, 8]:
        maps[f"rows_count_{width}"] = event(30, body(count_wire=packed(17, width)))
    broken = bytearray(maps["rows_write_two"])
    broken[-1] ^= 1
    maps["rows_bad_crc"] = bytes(broken)
    format_bytes = bytearray(fde()[:-4])
    format_bytes[76 + 29] = 8
    maps["fde_rows_old_header"] = bytes(format_bytes) + struct.pack("<I", zlib.crc32(format_bytes))
    return maps


def generated_files():
    lines = ["// Copyright 2026 Noverberrain.", "// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/generate_rows_event_fixtures.py."]
    manifest = {}
    for name, data in fixtures().items():
        lines.extend(["", "///|", f"let {name} : Bytes = ["])
        for start in range(0, len(data), 12):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[start:start + 12]) + ",")
        lines.append("]")
        manifest[name] = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    return {ROOT / "rows_event_fixture_test.mbt": "\n".join(lines) + "\n",
            ROOT / "fixtures" / "rows-event" / "manifest.json": json.dumps(manifest, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in generated_files().items():
        if args.check:
            def normalize(text):
                return re.sub(r",([\)\]])", r"\1", re.sub(r"\s+", "", text))
            if normalize(path.read_text(encoding="utf-8")) != normalize(expected):
                raise SystemExit(f"fixture differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {len(fixtures())} ROWS-event fixtures")


if __name__ == "__main__":
    main()
